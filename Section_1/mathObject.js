// Section 1 - Math Object

// 1. Random Number
console.log("1. Random Number:");
console.log(Math.random());


// 2. Random Whole Number (1 to 10)
console.log("2. Random Whole Number (1 to 10):");
console.log(Math.floor(Math.random() * 10) + 1);


// 3. Round a Number
console.log("3. Round 4.6:");
console.log(Math.round(4.6));


// 4. Floor and Ceil
console.log("4. Floor and Ceil:");
console.log("Floor:", Math.floor(7.3));
console.log("Ceil:", Math.ceil(7.3));


// 5. Absolute Value
console.log("5. Absolute Value:");
console.log(Math.abs(-25));


// 6. Power and Square Root
console.log("6. Power and Square Root:");
console.log("Power:", Math.pow(2, 3));
console.log("Square Root:", Math.sqrt(64));


// 7. Minimum and Maximum
console.log("7. Minimum and Maximum:");
console.log("Minimum:", Math.min(10, 25, 5, 18));
console.log("Maximum:", Math.max(10, 25, 5, 18));